// The timeline model: a pure function of the kit's schedule and the raw story.
// It adds only what drawing and editing need: lanes, each beat clip's source path in the raw story
// (`/scenes/2/beats/1`, or `/scenes/2/variants/9x16/beats/1` when that format's variant has beats),
// and whether a thing can be edited and why not. No timing is computed here: every time is the
// schedule's. Browser-safe: imports nothing but the kit's schedule.js and scripts/lib/cues.mjs.
//
// Which schedule: the KIT's schedule of `story` in `format`, as the mounted piece draws it:
// runtime/kit/schedule.js schedule(forFormat → resolveStory → addImplicitPlays, style, { patterns, each }),
// with `each` read from the layout (data-each children, data-stagger). In the studio that is the
// `schedule` the mounted kit returns (runtime/kit/kit.js mount → api.schedule), or the same call made in
// the page while a drag is in flight. It is NOT the gate's schedule that scripts/check/timing.mjs takes
// (built with { patterns } only, no `each`); the studio builds that one separately for timingRules.
//
// timelineModel(schedule, story, { format, grid }) → { kind, duration, scenes, lanes, grid }
//   story    the raw story (not resolved). Schedule scenes pair with story scenes by position (the
//            schedule keeps the story's order), so duplicate scene ids still map to the right scene; a
//            schedule whose scenes are not the story's, position by position, is refused (throws).
//   format   the schedule's format. Required (throws) when any scene has `variants[*].beats`, since
//            paths depend on it; otherwise it defaults to story.formats[0] (it then picks only the
//            variant layout shown on each scene).
//   grid     a parsed beats.json: `{ bpm?, beats, strong?, downbeats? }` or a bare array of times;
//            strong[] (times or { t }) when non-empty, else downbeats[].
//   scenes[] = { id, index, start, end, duration, layout, cut, move, path, editable: { duration, order }, reason? }
//   lanes[]  = { id, kind: 'slot'|'cues'|'moves', label, clips }: `slot:<name>` per slot name in
//              first-appearance order, then `cues`, then `moves` (camera moves, ambient moves, screen actions)
//   clip     = { id, kind: 'beat'|'cue'|'move'|'screen', scene, sceneStart, start, end, label, fx, selector,
//                path, segments: { enter, rest, emphasis?, exit?, ret? }, editable: { at, out }, reason?,
//                parent?, itemIndex?, beat? }
//     itemIndex: a beat clip's index in schedule.items. beat: on cue, move and screen clips, the path of
//     the beat they play on (null for a camera move). reason: why the clip cannot be edited, or, on an
//     editable beat clip, what is wrong with it ('out before at: …': its exit starts before its
//     entrance; the clip is then drawn from its start to its landing, never backwards).
// A deck's model is in presses (a press p spans [p − 1, p]) and is read-only.
import { eachParts } from '../../runtime/kit/schedule.js';
import { beatsOf } from '../lib/cues.mjs';

const ms = (x) => Math.round(x * 1000) / 1000;
const DECK = 'decks are read-only in the studio';
const CHILD = 'a cascade child moves with its beat; drag the cascade';
const BACKWARDS = 'out before at: its exit starts before its entrance; set out after at';
const READ_ONLY_KIND = { cue: 'a cue plays on its beat; move the beat', move: 'a move spans its scene; edit the scene or the beat', screen: 'screen actions are edited in the story file' };

// A1's beatPath shape and escaping (scripts/studio/ops.js), by scene index rather than id: the
// variant's beats when that format's variant defines a beats array.
const esc = (k) => String(k).replace(/~/g, '~0').replace(/\//g, '~1');
const variantBeats = (sc, format) => (format != null && Array.isArray(sc.variants?.[format]?.beats) ? sc.variants[format].beats : null);
const beatPath = (story, i, j, format) => (variantBeats(story.scenes[i], format) ? `/scenes/${i}/variants/${esc(format)}/beats/${j}` : `/scenes/${i}/beats/${j}`);
const patternName = (ref) => String(ref ?? '').split('/').pop();
const trim = (s) => { const t = String(s).replace(/\s+/g, ' ').trim(); return t.length > 24 ? `${t.slice(0, 23).trimEnd()}…` : t; };
const labelOf = (text, fx) => (text != null && String(text).trim() ? trim(text) : patternName(fx));

function readOnlyReason(story) {
  if (story.kind === 'deck') return DECK;
  if (story.generator) return `generated by ${story.generator}; edit its input and run it again`;
  return null;
}

export function timelineModel(sch, story, { format, grid } = {}) {
  if (format == null) {
    const v = story.scenes.find((sc) => Object.values(sc.variants ?? {}).some((x) => Array.isArray(x?.beats)));
    if (v) throw new TypeError(`timelineModel: pass { format }: scene "${v.id}" has variant beats, so its beat paths depend on the format`);
    format = story.formats?.[0];
  }
  if (sch.scenes.length !== story.scenes.length || sch.scenes.some((s, i) => s.id !== story.scenes[i].id)) {
    throw new Error(`timelineModel: the schedule is not of this story (schedule scenes ${sch.scenes.map((s) => s.id).join(',')}; story scenes ${story.scenes.map((s) => s.id).join(',')})`);
  }
  const deck = sch.kind === 'deck';
  const lock = readOnlyReason(story);
  const L = sch.pressLengths ?? [];
  const pos = (press, at) => (L[press] > 0 ? press - 1 + at / L[press] : press);

  const scenes = sch.scenes.map((s, i) => {
    const raw = story.scenes[i];
    const v = raw.variants?.[format];
    return {
      id: s.id, index: i, start: s.start, end: s.end, duration: deck ? raw.presses : raw.duration,
      layout: v?.layout ?? raw.layout, cut: s.cut?.pattern ? { pattern: s.cut.pattern, d: s.cut.d } : null, move: s.move ?? null,
      path: `/scenes/${i}`, editable: { duration: !lock, order: !lock }, ...(lock ? { reason: lock } : {}),
    };
  });

  // Items come per scene in story order, one per beat, a cascade's children right after their parent.
  // A beat item belongs to the first scene of its id that still has beats left to match.
  const positions = new Map();
  for (const s of scenes) positions.set(s.id, [...(positions.get(s.id) ?? []), s.index]);
  const beatCount = story.scenes.map((sc) => (variantBeats(sc, format) ?? sc.beats ?? []).length);
  const cursor = new Map();
  const nextBeat = (id) => {
    const ps = positions.get(id), c = cursor.get(id) ?? { p: 0, used: 0 };
    while (c.p < ps.length - 1 && c.used >= beatCount[ps[c.p]]) { c.p++; c.used = 0; }
    cursor.set(id, c);
    return [scenes[ps[c.p]], c.used++];
  };

  const slotLanes = new Map();
  const parents = new Map();
  const beatsBy = [];   // [{ clip, it, sc }] for the cascade parents and plain beats, to link cues and moves
  sch.items.forEach((it, n) => {
    let sc, j, id, parent, k = 0;
    if (it.parent) {
      parent = parents.get(it.parent);
      ({ sc, j } = parent);
      k = parent.kids++;
      id = `${parent.clip.id}.${k}`;
    } else {
      [sc, j] = nextBeat(it.scene);
      id = `beat:${sc.index}.${j}`;
    }
    const path = beatPath(story, sc.index, j, format);
    const own = it.parent ?? it;   // the cascade parent owns the exit, the emphasis and the return
    const span = deck
      ? (at, d) => (it.beat.step === 0 ? [it.press, it.press] : [pos(it.press, at), pos(it.press, ms(at + d))])
      : (at, d) => [at, ms(at + d)];
    const enter = deck ? span(it.at, it.d) : span(it.start, it.d);
    const exit = own.exit ? (deck ? [pos(own.exit.press, 0), pos(own.exit.press, own.exit.d)] : span(own.exit.start, own.exit.d)) : null;
    const ret = own.ret ? span(own.ret.start, own.ret.d) : null;
    const end = Math.max(enter[1], exit ? exit[1] : sc.end);
    const restEnd = Math.min(exit ? exit[0] : sc.end, ret ? ret[0] : Infinity);
    const segments = { enter, rest: [enter[1], Math.max(enter[1], restEnd)] };
    if (!it.parent && own.emphasis) segments.emphasis = deck ? [pos(it.press, own.emphasis.at), pos(it.press, ms(own.emphasis.at + own.emphasis.d))] : span(own.emphasis.start, own.emphasis.d);
    if (exit) segments.exit = exit;
    if (ret) segments.ret = ret;
    let label = labelOf(it.beat.text, it.fx);
    if (it.parent) {
      const parts = eachParts(it.beat.text, it.beat.params?.sep);
      if (parts.length === it.parent.each.n && parts[k] != null) label = trim(parts[k]);
    }
    const reason = lock ?? (it.parent ? CHILD : null);
    const flaw = !reason && exit && exit[0] < enter[0] ? BACKWARDS : null;
    const clip = {
      id, kind: 'beat', scene: it.scene, sceneStart: sc.start, start: enter[0], end, label, fx: it.fx, selector: it.selector, path, segments,
      editable: { at: !reason, out: !reason }, ...(reason || flaw ? { reason: reason ?? flaw } : {}), ...(it.parent ? { parent: parent.clip.id } : {}), itemIndex: n,
    };
    if (!it.parent) { parents.set(it, { sc, j, clip, kids: 0 }); beatsBy.push({ clip, it, sc }); }
    const lane = `slot:${it.slot}`;
    if (!slotLanes.has(lane)) slotLanes.set(lane, { id: lane, kind: 'slot', label: it.slot, clips: [] });
    slotLanes.get(lane).clips.push(clip);
  });

  // Cues and moves come from the schedule's events (an emphasis is drawn on its beat, not here). Each
  // links to the beat it plays on: same scene and selector, the beat with that cue (the nearest in
  // time), that ambient pattern (the nearest), or that screen action (the latest that starts before it).
  const whenItem = (it) => (deck ? pos(it.press, it.at ?? 0) : it.start);
  const whenEvent = (e) => (deck ? e.from ?? pos(e.press, e.at ?? 0) : e.t);
  const nearest = (xs, t) => xs.reduce((a, x) => (!a || Math.abs(whenItem(x.it) - t) < Math.abs(whenItem(a.it) - t) ? x : a), null);
  function beatOf(kind, e) {
    const mine = beatsBy.filter((b) => b.it.scene === e.scene && b.it.selector === e.selector);
    const t = whenEvent(e);
    if (kind === 'cue') return nearest(mine.filter((b) => b.it.beat.cue === e.cue), t);
    if (kind === 'screen') {
      const xs = mine.filter((b) => (b.it.beat.screen ?? []).some((a) => a.do === e.pattern));
      return xs.filter((b) => whenItem(b.it) <= t + 1e-9).pop() ?? nearest(xs, t);
    }
    if (e.ambient) return nearest(mine.filter((b) => b.it.fx === e.pattern), t);
    return null;
  }
  const sceneOfEvent = (e) => {
    const xs = scenes.filter((s) => s.id === e.scene);
    return xs.filter((s) => s.start <= whenEvent(e) + 1e-9).pop() ?? xs[0];
  };
  const cues = [], moves = [];
  const count = new Map();
  for (const e of sch.events) {
    let kind = null;
    if (e.kind === 'cue') kind = 'cue';
    else if (e.kind === 'move' && e.screen) kind = 'screen';
    else if (e.kind === 'move' && (e.ambient || e.selector === `[data-scene="${e.scene}"] .mm-camera`)) kind = 'move';
    if (!kind) continue;
    const b = beatOf(kind, e);
    const sc = b?.sc ?? sceneOfEvent(e);
    if (!sc) continue;
    const key = `${kind}:${sc.index}`;
    const k = count.get(key) ?? 0;
    count.set(key, k + 1);
    const start = deck ? e.from : e.t, end = deck ? e.to : ms(e.t + e.d);
    const fx = kind === 'cue' ? `sound/${e.cue}` : e.pattern;
    const reason = lock ?? READ_ONLY_KIND[kind];
    (kind === 'cue' ? cues : moves).push({
      id: `${key}.${k}`, kind, scene: e.scene, sceneStart: sc.start, start, end, label: kind === 'cue' ? e.cue : patternName(fx), fx, selector: e.selector,
      path: null, segments: { enter: [start, start], rest: [start, end] }, editable: { at: false, out: false }, reason, beat: b?.clip.path ?? null,
    });
  }

  const g = grid && !Array.isArray(grid) ? grid : {};
  const strong = Array.isArray(g.strong) && g.strong.length ? g.strong.map((s) => (typeof s === 'number' ? s : s.t)) : g.downbeats ?? [];
  return {
    kind: story.kind,
    duration: deck ? sch.presses : sch.duration,
    scenes,
    lanes: [...slotLanes.values(), { id: 'cues', kind: 'cues', label: 'Cues', clips: cues }, { id: 'moves', kind: 'moves', label: 'Moves', clips: moves }],
    grid: { bpm: g.bpm ?? story.audio?.bpm ?? null, beats: grid ? beatsOf(grid) ?? [] : [], strong: grid ? strong : [] },
  };
}

// A stage click to its beat: the beat clip whose selector is the clicked selector or an ancestor of
// it (the first such beat when two beats share a slot), else the scene, else null. "Ancestor" means
// the clicked selector continues the beat's with a space, `>`, `:`, `[`, `.` or `#` (not `+` or `~`,
// which name a sibling).
const INSIDE = new Set([' ', '>', ':', '[', '.', '#']);
export function pathForSelector(model, selector) {
  if (typeof selector !== 'string') return null;
  const within = (sel) => selector === sel || (selector.startsWith(sel) && INSIDE.has(selector[sel.length]));
  let best = null;
  for (const lane of model.lanes) {
    if (lane.kind !== 'slot') continue;
    for (const c of lane.clips) {
      if (c.parent || !within(c.selector)) continue;
      if (!best || c.selector.length > best.selector.length) best = c;
    }
  }
  if (best) return best.path;
  const sc = model.scenes.find((s) => within(`[data-scene="${s.id}"]`));
  return sc ? sc.path : null;
}
