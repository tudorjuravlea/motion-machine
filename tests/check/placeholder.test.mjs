// G-PLACEHOLDER (SPEC §7): visible text, ::before/::after text and the <text> of shipped SVGs.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { gate, failsOnly } from './_harness.mjs';
import { PLACEHOLDER, svgDataUris, svgTexts } from '../../scripts/check/G-PLACEHOLDER.mjs';

const run = gate();

test('G-PLACEHOLDER/text: a TODO on screen at a rest', async () => {
  const r = failsOnly(await run('G-PLACEHOLDER/text'), 'G-PLACEHOLDER');
  assert.equal(r.evidence.measured, 'TODO');
  assert.match(r.evidence.selector, /data-scene="style"/);
});

// A film scene whose last arrival is still running at its cut has no rest. W-SCENE-END only warns,
// so the frame-sampling rules also read each such scene at its last instant.
const NO_REST = ['W-SCENE-END', 'W-HOLD', 'W-DEAD', 'W-READ', 'W-QUIET', 'W-EMPTY'];

test('G-PLACEHOLDER/no-rest: a TODO in a scene with motion across its cut fails', async () => {
  const r = failsOnly(await run('G-PLACEHOLDER/no-rest'), 'G-PLACEHOLDER', { inherent: NO_REST });
  assert.equal(r.evidence.measured, 'TODO');
  assert.match(r.evidence.selector, /data-scene="style"/);
});

test('G-PLACEHOLDER/hard-end: placeholder text on the end card of a film that ends in motion fails', async () => {
  const r = failsOnly(await run('G-PLACEHOLDER/hard-end'), 'G-PLACEHOLDER', { inherent: NO_REST });
  assert.equal(r.evidence.measured, '{{');
  assert.match(r.evidence.selector, /data-scene="close"/);
});

test('G-PLACEHOLDER/transient: a placeholder that appears and leaves between rests is read from the story', async () => {
  const r = failsOnly(await run('G-PLACEHOLDER/transient'), 'G-PLACEHOLDER', { inherent: ['W-DEAD', 'W-READ', 'W-HOOK', 'W-EMPTY'] });
  assert.equal(r.evidence.file, 'story.json');
  assert.equal(r.evidence.selector, 'scenes[1].beats[0].text');
  assert.equal(r.evidence.measured, 'TODO');
});

test('G-PLACEHOLDER/pseudo: a TODO generated by ::after', async () => {
  const r = failsOnly(await run('G-PLACEHOLDER/pseudo'), 'G-PLACEHOLDER');
  assert.match(r.evidence.selector, /::after$/);
});

test('G-PLACEHOLDER/svg: a TODO inside a shipped SVG', async () => {
  const r = failsOnly(await run('G-PLACEHOLDER/svg'), 'G-PLACEHOLDER');
  assert.equal(r.evidence.file, 'assets/badge.svg');
  assert.equal(r.evidence.measured, 'TODO');
});

test('the placeholder forms; SVG text and data: URIs are read', () => {
  for (const s of ['TODO', 'Lorem ipsum', 'XXX', '{{name}}', '[…]', '[...]']) assert.ok(PLACEHOLDER.test(s), s);
  assert.ok(!PLACEHOLDER.test('Povești în mișcare'));
  assert.deepEqual(svgTexts('<svg><text x="1">Hello <tspan>lorem</tspan></text></svg>').map((t) => t.text), ['Hello lorem']);
  const css = `.a { background: url("data:image/svg+xml,${encodeURIComponent('<svg><text>XXX</text></svg>')}"); }`;
  assert.deepEqual(svgDataUris(css).flatMap((d) => svgTexts(d.svg)).map((t) => t.text), ['XXX']);
});

test('G-PLACEHOLDER/marker: ::marker content is read', async () => {
  const r = failsOnly(await run('G-PLACEHOLDER/marker'), 'G-PLACEHOLDER');
  assert.equal(r.evidence.measured, 'TODO');
  assert.match(r.evidence.selector, /data-slot="sub"\]::marker$/);
});

test('G-PLACEHOLDER/entity: character references are decoded before the SVG scan', async () => {
  const r = failsOnly(await run('G-PLACEHOLDER/entity'), 'G-PLACEHOLDER');
  assert.equal(r.evidence.file, 'assets/badge.svg');
  assert.equal(r.evidence.measured, 'TODO');
});

test('every XML entity form: named, decimal, hex, DTD-declared (nested, carrying markup), CDATA, foreignObject', () => {
  const one = (svg) => svgTexts(svg).map((t) => t.text);
  assert.deepEqual(one('<svg><text>T&#79;DO &amp; l&#x6F;rem &lt;b&gt;</text></svg>'), ['TODO & lorem <b>']);
  assert.deepEqual(one('<!DOCTYPE svg [<!ENTITY t "T&#79;"><!ENTITY w "&t;DO">]><svg><text>&w; now</text></svg>'), ['TODO now']);
  assert.deepEqual(one('<!DOCTYPE svg [<!ENTITY note "<text>XXX</text>">]><svg>&note;</svg>'), ['XXX']);
  assert.deepEqual(one('<svg><text><![CDATA[lorem & <ipsum>]]></text></svg>'), ['lorem & <ipsum>']);
  assert.deepEqual(one('<svg><foreignObject><div xmlns="http://www.w3.org/1999/xhtml">{{name}}</div></foreignObject></svg>'), ['{{name}}']);
  assert.ok(PLACEHOLDER.test(one('<svg><text>&#x54;&#x4F;&#x44;&#x4F;</text></svg>')[0]));
});
